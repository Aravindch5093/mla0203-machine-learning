def calculate_entropy(data):
    """Calculates the total entropy of a dataset distribution."""
    total_records = len(data)
    if total_records == 0:
        return 0
    counts = {}
    for row in data:
        label = row[-1]
        counts[label] = counts.get(label, 0) + 1

    entropy = 0.0
    for label in counts:
        prob = counts[label] / total_records
        entropy -= prob * math.log2(prob)
    return entropy

def calculate_information_gain(data, attr_idx):
    """Calculates the Information Gain of a specific attribute."""
    total_entropy = calculate_entropy(data)
    total_records = len(data)
    partitions = {}
    for row in data:
        val = row[attr_idx]
        if val not in partitions:
            partitions[val] = []
        partitions[val].append(row)

    subset_entropy = 0.0
    for val, subset in partitions.items():
        prob = len(subset) / total_records
        subset_entropy += prob * calculate_entropy(subset)

    return total_entropy - subset_entropy

def build_id3_tree(data, available_attrs, attr_names):
    """Recursively builds the decision tree dict infrastructure."""
    labels = [row[-1] for row in data]

    if len(set(labels)) == 1:
        return labels[0]

    if not available_attrs:
        return max(set(labels), key=labels.count)

    best_attr_idx = max(available_attrs, key=lambda idx: calculate_information_gain(data, idx))
    best_attr_name = attr_names[best_attr_idx]

    tree = {best_attr_name: {}}

    attr_values = set(row[best_attr_idx] for row in data)

    remaining_attrs = [idx for idx in available_attrs if idx != best_attr_idx]
    for val in attr_values:
        sub_data = [row for row in data if row[best_attr_idx] == val]

        if not sub_data:
            tree[best_attr_name][val] = max(set(labels), key=labels.count)
        else:
            tree[best_attr_name][val] = build_id3_tree(sub_data, remaining_attrs, attr_names)

    return tree

def classify_sample(tree, sample, attr_names):
    """Traverses the generated tree dictionary to classify a sample instance."""

    if not isinstance(tree, dict):
        return tree

    root_node = list(tree.keys())[0]
    attr_idx = attr_names.index(root_node)
    sample_val = sample[attr_idx]

    subtree = tree[root_node].get(sample_val)

    if subtree is None:
        return "Unknown Configuration (Cannot Classify)"

    return classify_sample(subtree, sample, attr_names)

