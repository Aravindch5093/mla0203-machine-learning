import pandas as pd
import numpy as np

def candidate_elimination(csv_file, positive_label="Yes"):
    df = pd.read_csv(csv_file)
    concepts = np.array(df.iloc[:, :-1]) # Attributes
    target = np.array(df.iloc[:, -1])    # Labels

    num_attributes = concepts.shape[1]

    specific_h = ['0'] * num_attributes
    for i, label in enumerate(target):
        if label == positive_label:
            specific_h = list(concepts[i].copy())
            break

    general_h = [['?' for _ in range(num_attributes)]]

    print(f"Initialization:")
    print(f"S0: {specific_h}")
    print(f"G0: {general_h}\n" + "-"*50)
    for i, h in enumerate(concepts):
        if target[i] == positive_label:
            print(f"Instance {i+1} is POSITIVE: {list(h)}")

            for x in range(num_attributes):
                if h[x] != specific_h[x]:
                    specific_h[x] = '?'

            general_h = [g for g in general_h if all(g[x] == '?' or g[x] == h[x] for x in range(num_attributes))]

        else:
            print(f"Instance {i+1} is NEGATIVE: {list(h)}")
            new_general_h = []

            for g in general_h:
                if any(g[x] != '?' and g[x] != h[x] for x in range(num_attributes)):
                    new_general_h.append(g)
                else:
                    for x in range(num_attributes):
                        if specific_h[x] != h[x] and specific_h[x] != '?':
                            g_new = g.copy()
                            g_new[x] = specific_h[x]
                            if g_new not in new_general_h:
                                new_general_h.append(g_new)

            general_h = [g for g in new_general_h if all(g[x] == '?' or g[x] == specific_h[x] for x in range(num_attributes))]

        print(f"S{i+1}: {specific_h}")
        print(f"G{i+1}: {general_h}\n" + "-"*50)

    return specific_h, general_h

final_s, final_g = candidate_elimination('training_data.csv')

print("\n" + "="*50)
print(f"Final Specific Boundary (S): {final_s}")
print(f"Final General Boundary (G):  {final_g}")
